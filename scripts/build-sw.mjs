// Writes out/sw.js after `next build`: precaches the exported app shell so the
// calculator opens offline. Live market APIs are never cached.
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';

const OUT = 'out';
const SHELL = ['/', '/manifest.webmanifest', '/icon.svg', '/apple-icon.png', '/favicon.ico', '/icon-192.png', '/icon-512.png', '/icon-maskable-512.png'];

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(entries.map((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)])));
  return files.flat();
}

const toUrl = (file) => '/' + relative(OUT, file).split(sep).join('/');

const all = await walk(OUT);
const statics = all.map(toUrl).filter((u) => u.startsWith('/_next/static/') && !u.endsWith('.map'));
const exists = new Set(all.map(toUrl));
const shell = SHELL.filter((u) => u === '/' || exists.has(u));
const precache = [...shell, ...statics].sort();

const hash = createHash('sha256');
for (const url of precache) {
  const file = url === '/' ? join(OUT, 'index.html') : join(OUT, ...url.slice(1).split('/'));
  hash.update(url).update(await readFile(file));
}
const version = hash.digest('hex').slice(0, 12);

const sw = `/* FMath service worker ${version}. Generated by scripts/build-sw.mjs; do not edit. */
const VERSION = ${JSON.stringify(version)};
const CACHE = 'fmath-' + VERSION;
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.filter((k) => k.startsWith('fmath-') && k !== CACHE).map((k) => caches.delete(k)));
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});

async function fromCache(request) {
  const cache = await caches.open(CACHE);
  return cache.match(request, { ignoreSearch: true });
}

async function put(request, response) {
  if (!response || !response.ok || response.type !== 'basic') return response;
  const cache = await caches.open(CACHE);
  await cache.put(request, response.clone());
  return response;
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  // live prices and outbound links always go to the network
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    // network first so a deploy shows up right away; the cached shell when offline
    event.respondWith(
      fetch(request)
        .then((res) => (url.pathname === '/' ? put(new Request('/'), res) : res))
        .catch(async () => (await fromCache(request)) || (await fromCache(new Request('/'))) || Response.error()),
    );
    return;
  }

  if (url.pathname.startsWith('/_next/static/')) {
    // content-hashed files never change
    event.respondWith(fromCache(request).then((hit) => hit || fetch(request).then((res) => put(request, res))));
    return;
  }

  // icons, manifest and the rest: serve cached, refresh in the background
  event.respondWith(
    fromCache(request).then((hit) => {
      const network = fetch(request)
        .then((res) => put(request, res))
        .catch(() => hit);
      return hit || network;
    }),
  );
});
`;

await writeFile(join(OUT, 'sw.js'), sw);
console.log(`sw.js ${version}: ${precache.length} files precached`);
